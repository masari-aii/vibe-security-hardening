#!/usr/bin/env python3
"""Build ALL-IN-ONE.md (single file for any LLM) and dist/vibe-security-hardening.zip (Claude skill upload)."""
import os, re, zipfile
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = lambda p: open(os.path.join(ROOT, p), encoding="utf-8").read()
skill = re.sub(r"^---\n.*?\n---\n", "", R("SKILL.md"), count=1, flags=re.S)
parts = [skill.strip()]
for f in ["scanner", "stacks", "encryption", "protection", "intrusion-alerts", "ai-security", "pdpl"]:
    parts.append(f"<!-- references/{f}.md -->\n" + R(f"references/{f}.md").strip())
parts.append("# scripts/scan.py\n\nSave as `scan.py` and run `python3 scan.py <project> [--url <your site>]`.\n\n```python\n" + R("scripts/scan.py").strip() + "\n```")
parts.append("# templates/security-scan.yml\n\n```yaml\n" + R("templates/security-scan.yml").strip() + "\n```")
out = "# Vibe Security Hardening — ALL-IN-ONE\n\nSingle-file edition for models and tools that cannot open the skill's separate files. Generated by tools/build.py; edit the source files, not this one.\n\n" + "\n\n---\n\n".join(parts) + "\n"
open(os.path.join(ROOT, "ALL-IN-ONE.md"), "w", encoding="utf-8").write(out)
os.makedirs(os.path.join(ROOT, "dist"), exist_ok=True)
zp = os.path.join(ROOT, "dist", "vibe-security-hardening.zip")
with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
    for rel in ["SKILL.md", "LICENSE"] + [f"references/{f}" for f in sorted(os.listdir(os.path.join(ROOT, "references")))] + \
               ["scripts/scan.py", "templates/security-scan.yml"]:
        z.write(os.path.join(ROOT, rel), "vibe-security-hardening/" + rel)
print("ALL-IN-ONE.md", len(out), "chars;", zp, os.path.getsize(zp), "bytes")
